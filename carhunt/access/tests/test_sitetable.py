import argparse
from pathlib import Path

import pytest

from carhunt.access import sitetable

FIX = Path(__file__).parent / "fixtures" / "sites"
ALPHA = FIX / "tablefix-alpha" / "site.yaml"
BETA = FIX / "tablefix-beta" / "site.yaml"


def _rows(text: str) -> list[list[str]]:
    lines = [ln for ln in text.splitlines() if ln.startswith("| ") and not ln.startswith("| site ")]
    return [[c.strip() for c in ln.strip("|").split(" | ")] for ln in lines]


def test_discover_env_override(monkeypatch):
    monkeypatch.setenv("CARHUNT_SITES_DIR", str(FIX))
    found = sitetable.discover()
    assert ALPHA in found and BETA in found
    assert found == sorted(found)


def test_discover_root_arg_beats_env(monkeypatch, tmp_path):
    monkeypatch.setenv("CARHUNT_SITES_DIR", str(tmp_path))
    assert sitetable.discover() == []
    assert ALPHA in sitetable.discover(FIX)


def test_render_two_fixtures():
    text = sitetable.render([BETA, ALPHA])
    assert "GENERATED by `carhunt browser site-table`" in text
    assert "Placeholder" in text  # fixtures are not the shipped carhunt/sites dir
    header = next(ln for ln in text.splitlines() if ln.startswith("| site "))
    assert header == "| " + " | ".join(sitetable.COLUMNS) + " |"
    rows = _rows(text)
    assert [r[0] for r in rows] == ["tablefix-alpha", "tablefix-beta"]  # sorted by site id
    a, b = rows
    assert all(len(r) == len(sitetable.COLUMNS) for r in rows)
    assert a[1] == "DataDome"
    assert a[2] == "http → plain-chrome"
    assert a[3] == "FR"
    assert a[4] == "≥12 s gap · ≤60/run"
    assert a[5] == "phone ≤40/day · send ≤10/day"
    assert a[6] == "for phone, message · sms-once (domestic mobile)"
    assert a[8] == "2026-11-06"
    assert a[9] == "stop at first 403/429/challenge; 404\\|410 = ad gone; never warm up on /"  # pipe escaped, multi-line notes joined
    assert b[2] == "http" and b[4] == "≥6 s gap · ≤2/h"
    assert b[3] == b[5] == b[6] == b[7] == b[9] == "—"


def test_render_is_deterministic():
    assert sitetable.render([ALPHA, BETA]) == sitetable.render([BETA, ALPHA])


def test_render_empty_has_placeholder_row():
    rows = _rows(sitetable.render([]))
    assert rows == [["—"] * len(sitetable.COLUMNS)]


def test_unknown_keys_are_kept():
    r = sitetable.row({"site": "x", "pace": {"min_gap_s": 5, "jitter_s": 3}, "caps": {"reveal_per_session": 3}})
    assert r[4] == "≥5 s gap · jitter_s 3"
    assert r[5] == "reveal_per_session 3"


def test_non_mapping_yaml_rejected(tmp_path):
    p = tmp_path / "bad" / "site.yaml"
    p.parent.mkdir()
    p.write_text("- just\n- a list\n")
    with pytest.raises(ValueError, match="mapping"):
        sitetable.render([p])


def _cli(*argv: str) -> int:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers()
    sitetable.register_cli(sub)
    args = ap.parse_args(["site-table", *argv])
    return args.func(args)


def test_cli_write_then_check(tmp_path, capsys):
    out = tmp_path / "site-table.md"
    assert _cli("--sites-dir", str(FIX), "--write", str(out)) == 0
    assert out.read_text() == sitetable.render([ALPHA, BETA])
    assert _cli("--sites-dir", str(FIX), "--check", str(out)) == 0
    out.write_text(out.read_text().replace("DataDome", "Akamai"))
    assert _cli("--sites-dir", str(FIX), "--check", str(out)) == 1
    assert "out of date" in capsys.readouterr().err
    assert _cli("--sites-dir", str(FIX), "--check", str(tmp_path / "missing.md")) == 1


def test_cli_stdout_and_main(capsys, monkeypatch):
    monkeypatch.setenv("CARHUNT_SITES_DIR", str(FIX))
    assert sitetable.main([]) == 0
    assert "tablefix-alpha" in capsys.readouterr().out


def test_write_and_check_are_exclusive():
    with pytest.raises(SystemExit):
        _cli("--write", "a", "--check", "b")
